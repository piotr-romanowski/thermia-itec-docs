#!/usr/bin/env python3
"""Generate the English-only register reference (REGISTERS.md) from the register map.

Reads the register map (same source of truth as the project's Home Assistant bridge) and emits a slim,
publication-ready table per slave, split into read / write, with NO non-English notes. Behaviour (encoding,
enums, bitfields, how to write) is documented in PROTOCOL.md, not here.

Usage:
    python tools/generate_registers.py [path/to/rejestry.yaml] [-o REGISTERS.md]

Default source: ../thermia/bridge/rejestry.yaml (the working copy next to this folder).
Requires PyYAML.
"""
import argparse
import re
from pathlib import Path

import yaml

KEY_RE = re.compile(r"^([RW])(\d+)\s+reg(\d+)$")
SLAVE_NAME = {
    2: "0x02 — indoor board",
    6: "0x06 — online-module transport (handshake ACK)",
    10: "0x0A — room-sensor slot (emulated)",
    15: "0x0F — online-gateway session",
    30: "0x1E — outdoor unit (Samsung EHS)",
}
# English names for the few entries whose source map still carries a non-English label (low-confidence
# registers). Keeps this public doc English without editing the working map.
NAME_OVERRIDES = {
    "R2 reg43013": "Unknown (constant ~16.8)",
    "W2 reg43022": "Operation mode / request (candidate)",
    "W2 reg43024": "Unknown (counter/phase?)",
    "W10 reg46021": "Room setpoint (push to sensor)",
    "W15 reg1092": "Cooling 1092 (unmapped)",
    "W15 reg1098": "Cooling 1098 (unmapped)",
    "W15 reg1099": "Cooling 1099 (unmapped)",
    "W30 reg1": "Set temperature",
}
# The 1210..1231 block is one post-boot transient phenomenon spread over 22 addresses (see PROTOCOL.md).
NAME_OVERRIDES.update({f"W15 reg{n}": "Post-boot transient block" for n in range(1210, 1232)})
# Safety net (language-neutral): any non-ASCII character in a name -> English placeholder, and counted.
# Source-language names that happen to be ASCII (e.g. abbreviations) are NOT auto-detected here by design;
# translate each one explicitly via NAME_OVERRIDES above. The pre-publication audit is the backstop.
NON_ENGLISH = re.compile(r"[^\x00-\x7f]")
STATUS_ORDER = {"confirmed": 0, "candidate": 1, "needs-reverify": 2, "unknown": 3}


def sign(entry):
    sb = entry.get("signed_bits")
    if sb:
        return f"signed ({sb}-bit)"
    try:
        if float(entry.get("scale", 1)) < 0:
            return "neg-scale"
    except (TypeError, ValueError):
        pass
    return ""


def fmt_scale(v):
    try:
        f = float(v)
    except (TypeError, ValueError):
        return str(v)
    return str(int(f)) if f == int(f) else f"{f:g}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src", nargs="?", default="../thermia/bridge/rejestry.yaml")
    ap.add_argument("-o", "--out", default="REGISTERS.md")
    args = ap.parse_args()

    data = yaml.safe_load(Path(args.src).read_text(encoding="utf-8"))
    regs = data["registers"] if isinstance(data, dict) and "registers" in data else data

    # group: slave -> kind(R/W) -> list of rows
    groups = {}
    for key, e in regs.items():
        m = KEY_RE.match(key)
        if not m:
            continue
        kind, slave, reg = m.group(1), int(m.group(2)), int(m.group(3))
        groups.setdefault(slave, {}).setdefault(kind, []).append((reg, key, e))

    placeholders = [0]

    def english_name(key, e):
        nm = NAME_OVERRIDES.get(key) or (e.get("name") or "")
        if NON_ENGLISH.search(nm):
            placeholders[0] += 1
            st = str(e.get("status", "unknown"))
            return f"(unnamed {st} register)"
        return nm

    counts = {"confirmed": 0, "candidate": 0, "unknown": 0, "needs-reverify": 0}
    for slave in groups:
        for kind in groups[slave]:
            for _, _, e in groups[slave][kind]:
                counts[str(e.get("status", "unknown"))] = counts.get(str(e.get("status", "unknown")), 0) + 1

    out = []
    out.append("# Thermia iTec Eco — register reference")
    out.append("")
    out.append("Auto-generated slim map (English only). Field meaning, encoding, enums, bitfields and how to")
    out.append("write are in [`PROTOCOL.md`](PROTOCOL.md) — this file is the address list.")
    out.append("")
    out.append("- **value = raw × scale**; `signed` marks two's-complement words (see PROTOCOL.md §2).")
    out.append("- **status**: `confirmed` verified on an Eco 8 · `candidate` observed, not fully verified · "
               "`unknown` seen, meaning open · `needs-reverify` previously trusted, since disputed.")
    out.append(f"- counts: confirmed {counts.get('confirmed',0)} · candidate {counts.get('candidate',0)} · "
               f"unknown {counts.get('unknown',0)} · needs-reverify {counts.get('needs-reverify',0)}.")
    out.append("")
    out.append("> Generated by `tools/generate_registers.py`. Do not edit by hand.")
    out.append("")

    for slave in sorted(groups):
        out.append(f"## Slave {SLAVE_NAME.get(slave, hex(slave))}")
        out.append("")
        for kind, title in (("R", "Read"), ("W", "Write")):
            rows = groups[slave].get(kind)
            if not rows:
                continue
            rows.sort(key=lambda r: (STATUS_ORDER.get(str(r[2].get("status", "unknown")), 9), r[0]))
            out.append(f"### {title}")
            out.append("")
            out.append("| Key | Name | Unit | Scale | Signed | Status |")
            out.append("|---|---|---|---|---|---|")
            for reg, key, e in rows:
                name = english_name(key, e).replace("|", "\\|")
                unit = (e.get("unit") or "").replace("|", "\\|")
                out.append(f"| `{key}` | {name} | {unit} | {fmt_scale(e.get('scale', 1))} "
                           f"| {sign(e)} | {e.get('status', 'unknown')} |")
            out.append("")

    Path(args.out).write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {args.out}: {sum(counts.values())} registers; {placeholders[0]} name(s) fell back to a placeholder")


if __name__ == "__main__":
    main()
